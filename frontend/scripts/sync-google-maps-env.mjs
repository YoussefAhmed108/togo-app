import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const envPath = path.join(rootDir, '.env');
const jsOutputPath = path.join(rootDir, 'src/config/maps.generated.ts');
const iosOutputPath = path.join(rootDir, 'ios/frontend/GoogleMapsAPIKey.generated.h');

function parseEnvFile(content) {
  const values = {};

  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const separatorIndex = line.indexOf('=');
    if (separatorIndex === -1) continue;

    const key = line.slice(0, separatorIndex).trim();
    let value = line.slice(separatorIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    values[key] = value;
  }

  return values;
}

function escapeForTypeScript(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function escapeForObjCString(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

if (!fs.existsSync(envPath)) {
  throw new Error(`Missing ${envPath}. Create frontend/.env first.`);
}

const env = parseEnvFile(fs.readFileSync(envPath, 'utf8'));
const apiKey = env.GOOGLE_MAPS_API_KEY || 'YOUR_GOOGLE_MAPS_API_KEY';

fs.mkdirSync(path.dirname(jsOutputPath), {recursive: true});
fs.writeFileSync(
  jsOutputPath,
  [
    '/** Auto-generated by scripts/sync-google-maps-env.mjs. Do not commit secrets. */',
    `export const GOOGLE_MAPS_API_KEY = '${escapeForTypeScript(apiKey)}';`,
    '',
  ].join('\n'),
);

fs.mkdirSync(path.dirname(iosOutputPath), {recursive: true});
fs.writeFileSync(
  iosOutputPath,
  [
    '// Auto-generated by scripts/sync-google-maps-env.mjs. Do not commit secrets.',
    '#ifndef GOOGLE_MAPS_API_KEY_GENERATED_H',
    '#define GOOGLE_MAPS_API_KEY_GENERATED_H',
    `#define GOOGLE_MAPS_API_KEY @"${escapeForObjCString(apiKey)}"`,
    '#endif',
    '',
  ].join('\n'),
);

console.log('Synced Google Maps API key from .env');
